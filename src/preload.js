'use strict';
const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('voiceKeys', {
  load: () => ipcRenderer.invoke('settings:load'),
  save: settings => ipcRenderer.invoke('settings:save', settings),
  profile: value=>ipcRenderer.invoke('profile:change',value),
  overlayDemo:()=>ipcRenderer.invoke('overlay:demo'),
  saveSample:value=>ipcRenderer.invoke('samples:save',value),
  readSample:id=>ipcRenderer.invoke('samples:read',id),
  deleteSample:id=>ipcRenderer.invoke('samples:delete',id),
  benchmarkSample:id=>ipcRenderer.invoke('samples:benchmark',id),
  reportSample:value=>ipcRenderer.invoke('samples:report',value),
  onQueue:callback=>ipcRenderer.on('queue-state',(_event,value)=>callback(value)),
  enrollStart: () => ipcRenderer.invoke('enroll:start'),
  enrollStop: () => ipcRenderer.invoke('enroll:stop'),
  saveLive: settings => ipcRenderer.invoke('settings:save', settings, { live: true }),
  setPrefs: value => ipcRenderer.invoke('ui:prefs', value),
  voiceOnset: at => ipcRenderer.send('voice:onset', at),
  exportProfiles: () => ipcRenderer.invoke('profiles:export'),
  importProfiles: () => ipcRenderer.invoke('profiles:import'),
  onMatched: callback => ipcRenderer.on('matched', (_event, value) => callback(value)),
  onConfigReplaced: callback => ipcRenderer.on('config-replaced', (_event, value) => callback(value)),
  onPrefs: callback => ipcRenderer.on('prefs-changed', (_event, value) => callback(value)),
  onRequestStart: callback => ipcRenderer.on('request-start', () => callback()),
  arm: enabled => ipcRenderer.invoke('listen:arm', enabled),
  ready: ready => ipcRenderer.invoke('voice:ready', ready),
  recognize: event => ipcRenderer.send('voice:recognition', event),
  diagnose: event => ipcRenderer.send('diagnostic', event),
  openLogs: () => ipcRenderer.invoke('logs:open'),
  prepareEngine: () => ipcRenderer.invoke('engine:prepare'),
  installModel: id => ipcRenderer.invoke('model:install', id),
  startEngine: value => ipcRenderer.send('engine:start', value),
  finishEngine: value => ipcRenderer.send('engine:finish', value),
  flushEngine: value => ipcRenderer.send('engine:flush', value),
  stopEngine: () => ipcRenderer.send('engine:stop'),
  audio: value => ipcRenderer.send('engine:audio', value),
  dataInfo: () => ipcRenderer.invoke('data:info'),
  dataOpen: () => ipcRenderer.invoke('data:open'),
  dataImport: () => ipcRenderer.invoke('data:import'),
  setAutostart: enabled => ipcRenderer.invoke('app:autostart', enabled),
  classifierAudio: value => ipcRenderer.send('classifier:audio', value),
  classifierStatus: () => ipcRenderer.invoke('classifier:status'),
  classifierMl: () => ipcRenderer.invoke('classifier:ml'),
  classifierTake: (word, samples, rate) => ipcRenderer.invoke('classifier:take', word, samples, rate),
  classifierBackground: (samples, rate) => ipcRenderer.invoke('classifier:background', samples, rate),
  classifierRemove: value => ipcRenderer.invoke('classifier:remove', value),
  classifierProfileWords: value => ipcRenderer.invoke('classifier:profile-words', value),
  classifierTrain: quality => ipcRenderer.invoke('classifier:train', quality),
  classifierCancel: () => ipcRenderer.invoke('classifier:cancel'),
  classifierSetup: () => ipcRenderer.invoke('classifier:setup'),
  onClassifierProgress: callback => ipcRenderer.on('classifier:progress', (_event, value) => callback(value)),
  onClassifierDone: callback => ipcRenderer.on('classifier:done', (_event, value) => callback(value)),
  onClassifierSetupLine: callback => ipcRenderer.on('classifier:setup-line', (_event, value) => callback(value)),
  onClassifierSetupDone: callback => ipcRenderer.on('classifier:setup-done', (_event, value) => callback(value)),
  startCapture: label => ipcRenderer.invoke('capture:start', label),
  stopCapture: () => ipcRenderer.invoke('capture:stop'),
  onCaptureAudio: callback => ipcRenderer.on('capture:audio', (_event, value) => callback(value)),
  onCaptureEnded: callback => ipcRenderer.on('capture:ended', (_event, value) => callback(value)),
  onState: callback => ipcRenderer.on('state', (_event, value) => callback(value)),
  onAction: callback => ipcRenderer.on('action', (_event, value) => callback(value)),
  onDecision: callback => ipcRenderer.on('decision', (_event, value) => callback(value)),
  onTranscript: callback => ipcRenderer.on('transcript', (_event, value) => callback(value)),
  onReleased: callback => ipcRenderer.on('released', (_event, value) => callback(value)),
  onInputState: callback => ipcRenderer.on('input-state', (_event, value) => callback(value)),
  onModelProgress: callback => ipcRenderer.on('model-progress', (_event, value) => callback(value)),
  onWarning: callback => ipcRenderer.on('warning', (_event, value) => callback(value))
});
